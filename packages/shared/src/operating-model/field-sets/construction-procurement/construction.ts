/**
 * Construction's fields: the programme and what delays it, the site log's
 * figures, pours and their cube samples, tests, inspections and
 * non-conformances, the safety registers, and snagging to handover.
 *
 * The schedule, the site log and the observations are modules of their own.
 * Nothing here copies them: a sheet reads their figures (`figure(...)`,
 * `field-figures.ts`) and holds only what they do not.
 *
 * Whatever there can be more than one of is a set of records, and every
 * count, total and standing above the records is worked out from them. The
 * acceptance of concrete and steel is arithmetic against rows of the rule
 * table (`rule-rows.ts`), each of which says it has not been verified.
 */

