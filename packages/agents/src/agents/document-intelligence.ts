/* Citation plumbing                                                     */
/* ==================================================================== */

interface CitationSpan {
  citedText: string;
  /** Only PDFs produce a page_location; other source types have no page. */
  startPage?: number;
}

/**
 * Pulls every citation off every text block in the response — and only the
 * ones the provider itself verified.
 *
 * `LlmCitation.verified` is the gate. A provider without `documentCitations`
 * may only ever return unverified citations, and an unverified citation is the
 * model repeating itself, not the document speaking. Skipping them here is
 * what guarantees `matchPageForQuote` can never return a page that nobody
 * checked, whatever route the call took.
 */
function collectCitations(content: LlmContentBlock[]): CitationSpan[] {
  const spans: CitationSpan[] = [];
  for (const block of content) {
    if (block.type !== 'text' || !block.citations) continue;
    for (const citation of block.citations) {
      if (!citation.verified) continue;
      // A verified citation with no page (a char_location on a text source) is
      // still kept: matchPageForQuote skips spans with no startPage, and
      // dropping them here would silently change which spans it considers.
      spans.push({ citedText: citation.quote, startPage: citation.page });
    }
  }
  return spans;
}

function normalizeForMatch(s: string): string {
  return s.toLowerCase().replace(/\s+/g, ' ').trim();
}

/** Word-overlap ratio for near-verbatim (punctuation/whitespace-only) matches. */
function wordOverlapRatio(a: string, b: string): number {
  const wa = new Set(a.split(' ').filter(w => w.length > 2));
  const wb = new Set(b.split(' ').filter(w => w.length > 2));
  if (wa.size === 0 || wb.size === 0) return 0;
  let shared = 0;
  for (const w of wa) if (wb.has(w)) shared += 1;
  return shared / Math.min(wa.size, wb.size);
}

/**
 * Finds the page a field's `quote` actually came from, by matching it
 * against the citations the API attached to the model's visible text. Returns
 * undefined when no citation backs the quote closely enough — the caller
 * treats that as "can't verify the page", never as license to guess one.
 */
function matchPageForQuote(quote: string, spans: CitationSpan[]): number | undefined {
  const q = normalizeForMatch(quote);
  if (!q) return undefined;

  for (const span of spans) {
    if (span.startPage === undefined) continue;
    const c = normalizeForMatch(span.citedText);
    if (c && (c.includes(q) || q.includes(c))) return span.startPage;
  }
  // Softer fallback for near-verbatim quotes that differ only in
  // punctuation/whitespace from the cited span.
  for (const span of spans) {
    if (span.startPage === undefined) continue;
    const c = normalizeForMatch(span.citedText);
    if (c && wordOverlapRatio(q, c) >= 0.6) return span.startPage;
  }
  return undefined;
}

