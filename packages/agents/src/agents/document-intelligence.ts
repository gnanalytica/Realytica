/**
 * Document intelligence agent.
 *
 * Replaces the fake `classifyDocument`/`extractFields` pair in
 * `packages/shared/src/engine.ts` (filename pattern-matching + deterministic
 * invented values) with a single real call to Claude against the actual
 * uploaded file: classify it into the real `DocumentKind` union and extract
 * its fields, each one grounded by a page citation from the source PDF.
 *
 * --- Why citations, not a self-reported page number -----------------------
 *
 * Anthropic's citations feature (`citations: { enabled: true }` on the
 * `document` content block) is generated by the API itself: it tracks which
 * part of the source PDF the model's *visible response text* actually drew
 * on, and attaches a `page_location` (1-indexed start/end page) to that span.
 * This is the only page number in this whole pipeline that isn't just the
 * model's word for it.
 *
 * Structured extraction, on the other hand, comes back as a tool call
 * (`tool_use.input`) — and citations are never attached to tool inputs, only
 * to `text` content blocks. So a tool schema field like "page" would just be
 * the model guessing, which is exactly what the brief rules out ("never
 * given a fabricated page number").
 *
 * The bridge between the two: the tool schema requires a `quote` per field —
 * a short verbatim excerpt from the document supporting that field's value —
 * and the system prompt instructs the model to *also* restate each field as
 * a grounded sentence in its visible text before calling the tool, closely
 * echoing the document's own wording. The API then attaches real citations to
 * that visible text. `collectCitations` gathers every citation off every text
 * block in the response; `matchPageForQuote` then looks up each field's
 * `quote` against that citation list (near-exact, then fuzzy word-overlap) to
 * find its real page. Only a field whose quote actually lands in a citation
 * gets a `sourcePage` — everything else is dropped or kept at low confidence
 * with no page, per the brief.
 *
 * --- What happens on a route that cannot do any of that -------------------
 *
 * This agent now goes through the provider port (`../providers`), and the port
 * declares capabilities rather than assuming them. On an OpenAI-compatible
 * route two of them are missing at once, and both matter here more than
 * anywhere else in the codebase:
 *
 *   pdf_input_unavailable  the PDF is extracted to text in-process and sent as
 *                          text. Layout, tables and page boundaries are gone,
 *                          and a scan with no text layer fails the call
 *                          outright rather than being sent as an empty
 *                          document for the model to fill in from imagination.
 *   citations_unavailable  there is no server-verified quotation, so there is
 *                          no page to attach to anything. `sourcePage` is
 *                          `undefined` on every field — never a guess, never
 *                          the model's own claim promoted to a fact.
 *
 * A field extracted this way is not the same evidence as one whose quote the
 * API located on page 3, so it must not look the same. Every field's
 * confidence is discounted and capped (see `discountUnverified`), the gaps go
 * onto `AgentRun.capabilityGaps`, and `describeGap`'s plain-language
 * consequence is appended to the notes a user actually reads. Degrading is
 * allowed. Degrading quietly is not.
 */

