const UNIT_TO_SQM: Record<string, number> = {
  sqm: 1,
  sqmt: 1,
  'sq.m': 1,
  sqft: 0.092903,
  'sq.ft': 0.092903,
  acre: 4046.86,
  acres: 4046.86,
  guntha: 101.171,
  gunthas: 101.171,
  cent: 40.4686,
  cents: 40.4686,
};

function parseFirstNumber(value: string): number | null {
  const match = value.replace(/,/g, '').match(/-?\d+(\.\d+)?/);
  return match ? parseFloat(match[0]) : null;
}

/** Best-effort area conversion to sqm; returns null when the unit isn't recognised
 * rather than guessing, since a wrong conversion is worse than no comparison. */
function toSqm(value: string, unit: string | null): number | null {
  if (!unit) return null;
  const n = parseFirstNumber(value);
  if (n === null) return null;
  const key = unit.trim().toLowerCase().replace(/\s+/g, '');
  const factor = UNIT_TO_SQM[key];
  return factor ? n * factor : null;
}

function normalizeKhataValue(value: string): KhataType | null {
  const v = value.toLowerCase();
  if (/\be[\s-]?khata\b/.test(v)) return 'e_khata';
  if (/\ba[\s-]?khata\b/.test(v)) return 'a_khata';
  if (/\bb[\s-]?khata\b/.test(v)) return 'b_khata';
  if (/form\s*9|gram\s*panchayat/.test(v)) return 'gram_panchayat_form_9_11';
  if (/no\s*khata|^none$/.test(v)) return 'none';
  return null;
}

function normalizeIdish(value: string): string {
  return value.toLowerCase().replace(/[\s/-]+/g, '');
}

interface RawExtractedField {
  key: string;
  label: string;
  value: string;
  unit: string | null;
  confidence: number;
  quote: string;
}

interface Disagreement {
  note: string;
  /** Confidence is capped at this value when the disagreement fires. */
  cappedConfidence: number;
}

/* ==================================================================== */
/* Degradation: what a field is worth when nothing verified it           */
/* ==================================================================== */

/**
 * How far a confidence falls when the route could not verify a single page.
 *
 * Two numbers rather than one because either alone leaves a hole. A bare
 * ceiling would leave a field the model already reported at 0.4 completely
 * untouched, which is the opposite of "visibly lower"; a bare multiplier would
 * let a 0.99 self-report land at 0.79 and still read as near-certain. Together
 * they guarantee that every field drops AND that none can present as better
 * than "worth checking" — which is exactly what an unverified extraction is.
 *
 * The values are deliberately harsher than the 0.35 cap applied to a single
 * unmatched quote on a verified route. That case is one field the citation
 * engine could not place in a document it did read; this one is a whole
 * document nothing checked at all.
 */
const UNVERIFIED_ROUTE_CONFIDENCE_FACTOR = 0.6;
const UNVERIFIED_ROUTE_CONFIDENCE_CEILING = 0.45;

function discountUnverified(confidence: number): number {
  return Math.round(Math.min(confidence * UNVERIFIED_ROUTE_CONFIDENCE_FACTOR, UNVERIFIED_ROUTE_CONFIDENCE_CEILING) * 100) / 100;
}

/**
 * The gaps that change what an extraction is *worth*, as opposed to what it
 * costs.
 *
 * Every gap this run hits is recorded on `AgentRun.capabilityGaps` and reaches
 * telemetry — that record is complete and stays complete. But the notes render
 * next to a khata number in a case file, and telling a buyer there that "the
 * stable prefix is re-sent and re-billed on every call" buries the sentence
 * that actually matters ("a quoted page can be wrong") in operational trivia.
 * These two are the ones that bear on whether the field can be trusted.
 */
const GROUNDING_GAPS: CapabilityGap[] = ['citations_unavailable', 'pdf_input_unavailable'];

/**
 * Compares one extracted field against what the user already recorded on the
 * case identity. This is deliberately scoped to what a *single* document call
 * can actually check against `identity` alone — extent/area, khata
 * classification, K-RERA number, and BBMP tax zone all have a direct
 * counterpart on `PropertyIdentity`/`KarnatakaAttributes`. Cross-document
 * reconciliation (e.g. a khata's owner name vs. a sale deed's buyer name)
 * needs more than one document's extraction and belongs to a later
 * orchestration step, not this per-document call.
 */
function checkDisagreement(field: RawExtractedField, identity: PropertyIdentity, kind: DocumentKind): Disagreement | null {
  const keyLower = field.key.toLowerCase();
  const labelLower = field.label.toLowerCase();
  const isAreaish = (pattern: RegExp) => pattern.test(keyLower) || pattern.test(labelLower);

  if (isAreaish(/extent|plot.?area|site.?area|land.?area/)) {
    const extractedSqm = toSqm(field.value, field.unit);
    if (extractedSqm !== null && identity.plotAreaSqm > 0) {
      const pctDiff = Math.abs(extractedSqm - identity.plotAreaSqm) / identity.plotAreaSqm;
      if (pctDiff > 0.05) {
        return {
          note: `${field.label} on the document (${field.value}${field.unit ? ` ${field.unit}` : ''} ≈ ${extractedSqm.toFixed(1)} sqm) differs from the recorded plot area (${identity.plotAreaSqm.toFixed(1)} sqm) by ${(pctDiff * 100).toFixed(0)}%.`,
          cappedConfidence: 0.5,
        };
      }
    }
  }

  if (isAreaish(/built.?up|carpet/)) {
    const extractedSqm = toSqm(field.value, field.unit);
    if (extractedSqm !== null && identity.builtUpAreaSqm > 0) {
      const pctDiff = Math.abs(extractedSqm - identity.builtUpAreaSqm) / identity.builtUpAreaSqm;
      if (pctDiff > 0.08) {
        return {
          note: `${field.label} on the document (${field.value}${field.unit ? ` ${field.unit}` : ''} ≈ ${extractedSqm.toFixed(1)} sqm) differs from the recorded built-up area (${identity.builtUpAreaSqm.toFixed(1)} sqm) by ${(pctDiff * 100).toFixed(0)}% — note the area basis (carpet/built-up/super built-up) may differ.`,
          cappedConfidence: 0.55,
        };
      }
    }
  }

  if (kind === 'khata_extract' && /khata.?type|classification/.test(keyLower)) {
    const expected = identity.karnataka?.khataType;
    if (expected && expected !== 'unknown') {
      const extracted = normalizeKhataValue(field.value);
      if (extracted && extracted !== expected) {
        return {
          note: `Khata extract states "${field.value}" but the case identity records khata type as ${KHATA_TYPE_LABEL[expected]} — this needs reconciling before it can be trusted.`,
          cappedConfidence: 0.4,
        };
      }
    }
  }

  if (kind === 'rera_registration' && /krera|rera.?number|registration.?number/.test(keyLower)) {
    const expected = identity.karnataka?.kreraNumber;
    if (expected && normalizeIdish(field.value) !== normalizeIdish(expected)) {
      return {
        note: `K-RERA number on the certificate ("${field.value}") does not match the number recorded on the case ("${expected}").`,
        cappedConfidence: 0.4,
      };
    }
  }

  if (kind === 'property_tax_receipt' && /zone/.test(keyLower)) {
    const expected = identity.karnataka?.bbmpTaxZone;
    if (expected && field.value.trim().toUpperCase() !== expected) {
      return {
        note: `Tax receipt records zone "${field.value}" but the case identity records BBMP zone ${expected}.`,
        cappedConfidence: 0.5,
      };
    }
  }

  return null;
}

