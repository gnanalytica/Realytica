const EXTRACTION_TOOL_NAME = 'record_document_extraction';

/**
 * A single non-streaming `messages.create`/`.stream()` call with a strict
 * tool is the whole shape of this agent's work — classify one document,
 * extract its fields, done. There's no multi-turn back-and-forth for the
 * model to drive (no client tool it needs a result from), so the tool runner
 * — built for looping a conversation until an agent finishes — has nothing
 * to loop over here; a single `create`/`.stream()` call is simpler and is
 * exactly what the SDK docs recommend for a one-shot structured-output ask.
 */
function buildExtractionTool(): Anthropic.Beta.BetaTool {
  return {
    name: EXTRACTION_TOOL_NAME,
    description:
      'Record the document classification and every field extracted from it. Every field must carry a verbatim supporting quote so its page can be verified against the source.',
    strict: true,
    input_schema: {
      type: 'object',
      additionalProperties: false,
      required: ['kind', 'kindConfidence', 'fields', 'notes'],
      properties: {
        kind: {
          type: 'string',
          enum: ALL_DOCUMENT_KINDS,
          description: 'The document kind this file actually is, from the catalogue in the system prompt.',
        },
        kindConfidence: { type: 'number', minimum: 0, maximum: 1, description: 'Your honest confidence in the classification.' },
        fields: {
          type: 'array',
          items: {
            type: 'object',
            additionalProperties: false,
            required: ['key', 'label', 'value', 'unit', 'confidence', 'quote'],
            properties: {
              key: { type: 'string', description: 'Short camelCase identifier, e.g. "registrationNumber".' },
              label: { type: 'string', description: 'Human-readable label, e.g. "Registration number".' },
              value: { type: 'string', description: 'The extracted value as plain text.' },
              unit: { type: ['string', 'null'], description: 'Unit of the value, e.g. "sqft", "INR" — null when the value has no unit.' },
              confidence: { type: 'number', minimum: 0, maximum: 1, description: 'Your honest confidence that this value is correct.' },
              quote: {
                type: 'string',
                description: 'A verbatim excerpt (<=20 words), copied exactly from the document, that states or directly supports this value.',
              },
            },
          },
        },
        notes: {
          type: 'string',
          description: 'Anything worth flagging — illegibility, internal inconsistency, inability to classify confidently. Empty string if none.',
        },
      },
    },
  };
}

