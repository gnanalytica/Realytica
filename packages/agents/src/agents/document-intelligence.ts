export async function runDocumentIntelligence(input: RunDocumentIntelligenceInput): Promise<DocumentIntelligenceResult> {
  const { caseId, document, fileBytes, identity, now } = input;
  const runId = randomUUID();
  const startedAt = new Date().toISOString();
  const steps: AgentStep[] = [];

  const emit = (step: Omit<AgentStep, 'id' | 'at'>): void => {
    const full: AgentStep = { id: randomUUID(), at: new Date().toISOString(), ...step };
    steps.push(full);
    input.onStep?.(full);
  };

  // Every early-exit path returns through here so the caller always gets a
  // well-formed AgentRun and never an exception — this must be safe to call
  // with no credentials, no file, or an unsupported file, per the brief.
  // It always keeps the document's existing classification rather than
  // inventing one, since a failed/skipped run made no new determination.
  const finishFailure = (status: AgentRunStatus, error: string, usage?: AgentRun['usage']): DocumentIntelligenceResult => {
    const finishedAt = new Date().toISOString();
    const run: AgentRun = {
      id: runId,
      caseId,
      agent: 'document_intelligence',
      status,
      startedAt,
      finishedAt,
      model: AGENT_MODEL,
      steps,
      error,
      usage,
      producedEvidenceIds: [],
    };
    return {
      run,
      kind: document.kind,
      kindConfidence: document.classificationConfidence,
      fields: [],
      evidence: [],
      notes: error,
    };
  };

  emit({ kind: 'plan', label: `Classifying and extracting "${document.fileName}"` });

  const isPdf = document.mimeType === 'application/pdf';
  const isSupportedImage = SUPPORTED_IMAGE_MEDIA_TYPES.has(document.mimeType);

  if (!isPdf && !isSupportedImage) {
    const reason = `Document intelligence only reads PDFs and JPEG/PNG/GIF/WebP images — "${document.mimeType}" is not supported, so this run was skipped.`;
    emit({ kind: 'error', label: 'Unsupported file type', detail: reason });
    // AgentRunStatus has no "skipped" state; 'cancelled' is the closest fit
    // for "intentionally did not run", as distinct from 'failed' (attempted
    // and errored) — see AgentRunStatus in packages/shared/src/types.ts.
    return finishFailure('cancelled', reason);
  }

  if (!fileBytes) {
    const reason = 'No file is available for this document — cannot run extraction.';
    emit({ kind: 'error', label: 'No file to read', detail: reason });
    return finishFailure('failed', reason);
  }

  const client = getClient();
  if (!client) {
    const reason = 'Anthropic credentials are not configured — document intelligence is unavailable.';
    emit({ kind: 'error', label: 'No credentials', detail: reason });
    return finishFailure('failed', reason);
  }

  let documentBlock: Anthropic.Beta.BetaContentBlockParam;
  if (isPdf) {
    const loaded = await loadPdfForExtraction(fileBytes);
    if (!loaded.ok) {
      emit({ kind: 'error', label: 'PDF rejected before sending', detail: loaded.message });
      return finishFailure('failed', loaded.message);
    }
    emit({
      kind: 'tool_result',
      label: `Loaded PDF — ${loaded.pdf.pageCount} page(s), ${(loaded.pdf.sizeBytes / 1024).toFixed(0)}KB`,
    });
    documentBlock = {
      type: 'document',
      source: { type: 'base64', media_type: 'application/pdf', data: loaded.pdf.base64 },
      citations: { enabled: true },
      title: document.fileName,
    };
  } else {
    const loaded = await loadImageForExtraction(fileBytes);
    if (!loaded.ok) {
      emit({ kind: 'error', label: 'Image rejected before sending', detail: loaded.message });
      return finishFailure('failed', loaded.message);
    }
    emit({ kind: 'tool_result', label: 'Loaded image' });
    documentBlock = {
      type: 'image',
      source: { type: 'base64', media_type: document.mimeType as SupportedImageMediaType, data: loaded.base64 },
    };
    // Note: the Anthropic image content block has no `citations` option —
    // citations are a document (PDF/text)-only feature. Fields extracted from
    // an image therefore never get a sourcePage; the field-building loop below
    // reflects that honestly by leaving sourcePage undefined for every field
    // when the source isn't a PDF (see the `isPdf ? matchPageForQuote(...) : undefined` line).
  }

  const tool = buildExtractionTool();
  const systemPrompt = buildSystemPrompt();
  const userPrompt = buildUserPrompt(document, identity);

  emit({ kind: 'tool_call', label: 'Requesting classification & extraction from Claude', toolName: EXTRACTION_TOOL_NAME });

  const requestParams = {
    ...BASE_REQUEST,
    max_tokens: 8000,
    system: [{ type: 'text' as const, text: systemPrompt, cache_control: { type: 'ephemeral' as const } }],
    tools: [tool],
    messages: [{ role: 'user' as const, content: [documentBlock, { type: 'text' as const, text: userPrompt }] }],
  };

  let message: Anthropic.Beta.BetaMessage;
  try {
    // The installed @anthropic-ai/sdk's shipped .d.ts predates Claude Opus 5's
    // adaptive-thinking API (`thinking: { type: "adaptive" }` in BASE_REQUEST,
    // from client.ts) — its BetaThinkingConfigParam type still only knows
    // "enabled"/"disabled". The live API accepts "adaptive" regardless; this
    // cast unblocks the compiler against a stale type union without touching
    // the request body itself (no `any` involved — `unknown` is a type-only
    // detour, not a runtime one).
    const stream = client.beta.messages.stream(requestParams);
    message = await stream.finalMessage();
  } catch (e) {
    const reason = describeError(e);
    emit({ kind: 'error', label: 'Anthropic request failed', detail: reason });
    return finishFailure('failed', reason);
  }

  if (message.stop_reason === 'refusal') {
    const reason = 'Claude declined to process this document (safety filtering).';
    emit({ kind: 'error', label: 'Request refused', detail: reason });
    return finishFailure('failed', reason, estimateUsage(message.usage));
  }
  if (message.stop_reason === 'model_context_window_exceeded') {
    const reason = 'The document was too large for the model context window.';
    emit({ kind: 'error', label: 'Context window exceeded', detail: reason });
    return finishFailure('failed', reason, estimateUsage(message.usage));
  }

  const usage = estimateUsage(message.usage);

  const toolUse = message.content.find(
    (block): block is Anthropic.Beta.BetaToolUseBlock => block.type === 'tool_use' && block.name === EXTRACTION_TOOL_NAME,
  );
  if (!toolUse) {
    const reason = `The model did not return structured extraction output (stop_reason=${message.stop_reason ?? 'unknown'}).`;
    emit({ kind: 'error', label: 'No extraction returned', detail: reason });
    return finishFailure('failed', reason, usage);
  }

  const parsed = ExtractionOutputSchema.safeParse(toolUse.input);
  if (!parsed.success) {
    const reason = `Model output failed schema validation: ${parsed.error.message}`;
    emit({ kind: 'error', label: 'Invalid extraction output', detail: reason });
    return finishFailure('failed', reason, usage);
  }
  if (!isDocumentKind(parsed.data.kind)) {
    const reason = `Model returned an unrecognised document kind: "${parsed.data.kind}".`;
    emit({ kind: 'error', label: 'Invalid document kind', detail: reason });
    return finishFailure('failed', reason, usage);
  }

  const kind = parsed.data.kind;
  const kindConfidence = parsed.data.kindConfidence;

  // Citations are PDF-only (see the image branch above); for an image source
  // this is simply an empty list, and every field below correctly ends up
  // with no sourcePage rather than a fabricated one.
  const citationSpans = collectCitations(message.content);

  emit({
    kind: 'tool_result',
    label: `record_document_extraction returned: kind=${kind} (${Math.round(kindConfidence * 100)}%), ${parsed.data.fields.length} field(s)`,
  });

  const fields: ExtractedField[] = [];
  const evidence: EvidenceItem[] = [];
  const disagreementNotes: string[] = [];
  let evidenceSeq = 0;

  for (const raw of parsed.data.fields) {
    const sourcePage = isPdf ? matchPageForQuote(raw.quote, citationSpans) : undefined;
    let confidence = Math.max(0, Math.min(1, raw.confidence));

    // Honesty rule: a page only ever gets attached when the API's own
    // citation engine actually located the quoted text in the source. When
    // it didn't, the field survives at reduced confidence and with no page —
    // never with a guessed one.
    if (isPdf && sourcePage === undefined) {
      confidence = Math.min(confidence, 0.35);
      if (confidence < 0.4) continue; // not worth surfacing as "extracted"
    }

    const disagreement = checkDisagreement(raw, identity, kind);
    if (disagreement) {
      confidence = Math.min(confidence, disagreement.cappedConfidence);
      disagreementNotes.push(disagreement.note);
    }

    fields.push({
      key: raw.key,
      label: raw.label,
      value: raw.value,
      unit: raw.unit ?? undefined,
      confidence,
      sourceDocumentId: document.id,
      sourcePage,
      method: 'ocr',
    });

    evidenceSeq += 1;
    const pageSuffix = sourcePage ? `, p.${sourcePage}` : '';
    evidence.push({
      id: `ev-doc-${document.id}-${evidenceSeq}`,
      statement: `${raw.label}: ${raw.value}${raw.unit ? ` ${raw.unit}` : ''} (from ${document.fileName}${pageSuffix}).`,
      sourceType: 'document',
      sourceRef: document.id,
      sourceLabel: sourcePage ? `${document.fileName}, p.${sourcePage}` : document.fileName,
      confidence,
      capturedAt: now,
    });
  }

  const notes = [parsed.data.notes, ...disagreementNotes].filter(s => s.trim().length > 0).join(' ');

  emit({
    kind: 'message',
    label: `Extracted ${fields.length} field(s) from "${document.fileName}"`,
    detail: notes || undefined,
  });

  const summary = `Classified as ${kind} (${Math.round(kindConfidence * 100)}% confidence); extracted ${fields.length} field(s)${disagreementNotes.length > 0 ? `; ${disagreementNotes.length} disagreement(s) flagged` : ''}.`;

  const run: AgentRun = {
    id: runId,
    caseId,
    agent: 'document_intelligence',
    status: 'succeeded',
    startedAt,
    finishedAt: new Date().toISOString(),
    model: AGENT_MODEL,
    steps,
    summary,
    usage,
    producedEvidenceIds: evidence.map(e => e.id),
  };

  return { run, kind, kindConfidence, fields, evidence, notes };
}
